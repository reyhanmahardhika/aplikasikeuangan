type TextState = { source: string; rendered: string };
type AttributeState = { source: string; rendered: string };

const textStates = new WeakMap<Text, TextState>();
const attributeStates = new WeakMap<Element, Map<string, AttributeState>>();
const translatedAttributes = ["placeholder", "title", "aria-label"];

function translateValue(value: string, language: UiLanguage = "en") {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const content = value.trim();
  if (!content) return value;
  const exact = language === "en" ? english[content] : indonesianCategories[content];
  if (exact) return `${leading}${exact}${trailing}`;
  if (language === "id") return value;
  for (const [pattern, replacement] of patterns) {
    const match = content.match(pattern);
    if (match) return `${leading}${replacement(...match)}${trailing}`;
  }
  return value;
}

function translateTextNode(node: Text, language: UiLanguage) {
  const current = node.nodeValue ?? "";
  let state = textStates.get(node);
  if (!state || current !== state.rendered) {
    state = { source: current, rendered: current };
    textStates.set(node, state);
  }
  const next = translateValue(state.source, language);
  state.rendered = next;
  if (current !== next) node.nodeValue = next;
}

function translateElement(element: Element, language: UiLanguage) {
  let states = attributeStates.get(element);
  if (!states) {
    states = new Map();
    attributeStates.set(element, states);
  }
  for (const attribute of translatedAttributes) {
    const current = element.getAttribute(attribute);
    if (current == null) continue;
    let state = states.get(attribute);
    if (!state || current !== state.rendered) {
      state = { source: current, rendered: current };
      states.set(attribute, state);
    }
    const next = translateValue(state.source, language);
    state.rendered = next;
    if (current !== next) element.setAttribute(attribute, next);
  }
}

function translateTree(root: Node, language: UiLanguage) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root as Text, language);
    return;
  }
  if (!(root instanceof Element) && !(root instanceof Document)) return;
  if (root instanceof Element) translateElement(root, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node as Text, language);
    else translateElement(node as Element, language);
    node = walker.nextNode();
  }
}

export function installUiTranslation(language: UiLanguage) {
  const nativeConfirm = window.confirm.bind(window);
  const nativeAlert = window.alert.bind(window);
  const nativePrompt = window.prompt.bind(window);
  window.confirm = (message?: string) => nativeConfirm(translateValue(String(message ?? ""), language));
  window.alert = (message?: unknown) => nativeAlert(translateValue(String(message ?? ""), language));
  window.prompt = (message?: string, defaultValue?: string) => nativePrompt(
    translateValue(String(message ?? ""), language),
    defaultValue
  );
  return () => {
    window.confirm = nativeConfirm;
    window.alert = nativeAlert;
    window.prompt = nativePrompt;
  };
}
